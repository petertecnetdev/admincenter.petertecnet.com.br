import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(process.cwd())
const read = path => readFileSync(resolve(root, path), 'utf8')
const failures = []
const check = (name, condition) => condition ? console.log(`✓ ${name}`) : (console.error(`✗ ${name}`), failures.push(name))

const main = read('src/main.jsx')
const styles = read('src/admin.css')
const app = read('src/App.jsx')
const index = read('index.html')
const responsive = read('src/AdminResponsive.css')
const responsiveV3 = read('src/AdminResponsiveV3.css')
const experience = read('src/AdminExperienceV2.css')
const appCss = read('src/App.css')
const establishmentsCss = read('src/AdminEstablishmentsPage.css')
const establishments = read('src/AdminEstablishmentsPageV2.jsx')
const usersCss = read('src/AdminUsersCenter.css')
const notificationsCss = read('src/NotificationsCenter.css')

const appImport = styles.indexOf("@import './App.css'")
const responsiveImport = styles.indexOf("@import './AdminResponsive.css'")
const experienceImport = styles.indexOf("@import './AdminExperienceV2.css'")
const uiKitImport = styles.indexOf("@import './AdminUiKit.css'")
const qualityImport = styles.indexOf("@import './AdminQualityLayer.css'")
const v3Import = styles.indexOf("@import './AdminResponsiveV3.css'")

check('global styles have a single application entry', main.includes("import './admin.css'") && !main.includes("import './App.css'"))
check('viewport meta is configured', /name="viewport"\s+content="[^"]*width=device-width/.test(index))
check('responsive foundation loads after base CSS', responsiveImport > appImport)
check('experience loads after responsive foundation', experienceImport > responsiveImport)
check('UI kit loads after experience', uiKitImport > experienceImport)
check('quality layer loads after UI kit', qualityImport > uiKitImport)
check('responsive V3 is the final contract layer', v3Import > qualityImport)
check('legacy polish layers are not loaded', !styles.includes('AdminNavigationStandard.css') && !styles.includes('AdminHamburgerPolish.css') && !styles.includes('AdminTopbarPolish.css'))
check('React owns active page state', app.includes('data-admin-page={activePage}') && app.includes('setActivePage'))
check('navigation supports browser history', app.includes("window.addEventListener('popstate'") && app.includes('writePageHistory'))
check('deep links map real slugs', app.includes('PAGE_FROM_SLUG') && app.includes('url.searchParams.set(\'page\', config.slug)'))
check('active page is announced', app.includes("aria-current={activePage === id ? 'page' : undefined}"))
check('sidebar exposes expanded/controls state', app.includes('aria-expanded={sidebarOpen}') && app.includes('aria-controls="admin-navigation"'))
check('sidebar has keyboard focus containment', app.includes('handleSidebarKeyDown') && app.includes("event.key !== 'Tab'"))
check('global command palette shortcut exists', app.includes("event.key.toLowerCase() === 'k'") && app.includes('setSearchOpen(true)'))
check('ecosystem search has an accessible name', app.includes('aria-label="Pesquisar no ecossistema"'))
check('search supports keyboard result navigation', app.includes("event.key === 'ArrowDown'") && app.includes("event.key === 'ArrowUp'"))
check('recent pages are persisted', app.includes('RECENT_PAGES_KEY') && app.includes('recentPages'))
check('favorite pages are persisted', app.includes('FAVORITE_PAGES_KEY') && app.includes('favoritePages'))
check('density preference is persisted', app.includes('DENSITY_PREF_KEY') && app.includes('compactMode'))
check('sidebar preference is persisted', app.includes('SIDEBAR_PREF_KEY') && app.includes('sidebarOpen'))
check('selected page resets viewport', app.includes("window.scrollTo({ top: 0, left: 0, behavior: 'auto' })"))
check('root surfaces cannot widen page', responsiveV3.includes('overflow-x:clip'))
check('dense data scrolls locally', responsiveV3.includes('.adm-datatable-scroll') && responsiveV3.includes('overflow-x:auto'))
check('financial table becomes cards on phones', responsive.includes(".table-wrap td:nth-child(1)::before { content: 'Aplicação'; }"))
check('notification history becomes cards on phones', responsive.includes(".notification-table td:nth-child(1)::before { content: 'Campanha'; }"))
check('mobile drawer respects viewport/safe area', experience.includes('width:min(360px,90vw)') && experience.includes('env(safe-area-inset-top)'))
for (const width of [320, 360, 390, 430, 1024, 1280, 1366, 1440]) check(`roadmap breakpoint ${width}px exists`, responsiveV3.includes(`max-width:${width}px`))
check('tablet breakpoint exists', responsiveV3.includes('max-width:820px'))
check('Full HD/ultrawide handling exists', responsiveV3.includes('min-width:1920px') && responsiveV3.includes('min-width:2560px'))
check('touch targets are at least 44px', responsiveV3.includes('--adm-touch:44px') && responsiveV3.includes('min-height:44px'))
check('focus-visible is explicit', responsiveV3.includes(':focus-visible'))
check('reduced motion is respected', responsiveV3.includes('prefers-reduced-motion:reduce'))
check('increased contrast is respected', responsiveV3.includes('prefers-contrast:more'))
check('base dashboard still has tablet drawer breakpoint', appCss.includes('@media(max-width:980px)'))
check('establishments reuses the objective user list mobile contract', establishments.includes('acu-simple-user__details') && usersCss.includes('@media(max-width:820px)') && establishmentsCss.includes('.aep-objective-search'))
check('notifications still has mobile layout breakpoint', notificationsCss.includes('@media(max-width:760px)'))
check('all management modules remain represented', ['dashboard','operations','agents','financial','applications','users','establishments','items','notifications','activity'].every(page => app.includes(`${page}:`) || app.includes(`'${page}'`)))

if (failures.length) {
  console.error(`\n${failures.length} regressão(ões) de responsividade/navegação detectada(s).`)
  process.exit(1)
}
console.log('\nAdmin Center responsive navigation contract validated.')
